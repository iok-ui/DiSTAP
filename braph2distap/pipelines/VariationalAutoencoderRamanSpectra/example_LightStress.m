%% EXAMPLE_LIGHTSTRESS
% Script example DIVA pipeline for light stress

clear variables %#ok<*NASGU>

%% Load Spectra Dataset
dproc = NNDatasetProcess_RamanSpectra( ...
    'RAW_DATA_DIR', [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'study_LightStress' filesep 'data'], ...
    'TRANSFORMATION_RULE', 'First derivative', ...
    'NORMALIZATION_RULE', 'Scale', ...
    'SCALE_FACTOR', 100, ...
    'STRESS_SEQ', {'WL', 'HL', 'LL', 'SH'}, ...
    'KIND_SEQ', {'AB2', 'CS', 'KL'}, ...
    'LOCATION_SEQ', {'loc1', 'loc2'}, ...
    'TARGETS_TO_REMOVE', {'ps'});

d_sp = dproc.get('D');

% announce memorizing start
fprintf('Memorizing all dataset inputs (may take a few minutes) ...%s', newline);
dproc.memorize('RAW_DATA');
d_sp.memorize('INPUTS');
fprintf('Finished memorizing all dataset inputs.%s', newline);

fprintf('Memorizing all dataset targets (may take a few minutes) ...%s', newline);
d_sp.memorize('TARGETS');
fprintf('Finished memorizing all dataset targets.%s', newline);

%% Choose the Number of Epochs by Cross-Validation
% all spectra of an acquisition (leaf location, label row 4) are kept in the same fold, as in train_vae.m
nncv = NNVariationalAutoencoderMLP_CV( ...
    'D', {d_sp}, ...
    'KFOLDS', 5, ...
    'FOLD_RULE', 'Grouped by replicate', ...
    'NEURONS_PER_LAYER', [64], ...
    'EPOCHS', 500, ...
    'BATCH', 40, ...
    'EARLY_STOP_RULE', 'Plateau or overfitting onset (first to occur)', ...
    'DIRECTORY_FIG', [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'study_LightStress'], ... % same folder as the evaluation below
    'FILE_PREFIX', 'LightStress');
nncv.get('TRAIN');

num_epochs = nncv.get('SELECTED_EPOCH');
fprintf('Number of epochs selected by cross-validation: %d%s', num_epochs, newline);

% export the tables (as in train_vae.m) and the figures justifying the number of epochs to DIRECTORY_FIG
nncv.get('EXPORT_RESULTS');
nncv.get('PLOT_EPOCH_SELECTION');

%% Train a Variational Autoencoder
nnvae = NNVariationalAutoencoderMLP('D', d_sp, 'NEURONS_PER_LAYER', nncv.get('NEURONS_PER_LAYER'), 'EPOCHS', num_epochs, 'BATCH', nncv.get('BATCH'));
nnvae.get('TRAIN')

%% Evaluate and Produce Manuscript figures
% spectra of the first measurement location (loc1) of each leaf, used for the figures and the peak analysis
%  as in the manuscript (the variational autoencoder above is trained on all locations)
dp_list = d_sp.get('DP_DICT').get('IT_LIST');
is_fig_location = false(size(dp_list));
for i = 1:1:numel(dp_list)
    labels = strtrim(cellstr(char(dp_list{i}.get('TARGET_CLASS')))); % species, stress, location, acquisition ID
    is_fig_location(i) = strcmp(labels{3}, 'loc1');
end
d_fig = NNDataset( ...
    'DP_CLASS', 'NNDataPoint_RamanSpectra', ...
    'DP_DICT', IndexedDictionary('IT_CLASS', 'NNDataPoint_RamanSpectra', 'IT_LIST', dp_list(is_fig_location)) ...
    );
fprintf('Spectra used for the figures (loc1): %d of %d%s', d_fig.get('DP_DICT').get('LENGTH'), numel(dp_list), newline);

nne = NNVariationalAutoencoderEvaluator_RS( ...
    'NN', nnvae, ...
    'D', d_fig, ...
    'DPROC', dproc, ...
    'RESOLUTION_CM', 6, ...
    'IDX_LABEL_KIND', 1, ...
    'IDX_LABEL_STRESS', 2, ...
    'IDX_LABEL_LOCATION', 3, ...
    'STRESS_SEQ', {'HL', 'WL', 'LL', 'SH'}, ...
    'STRESS_LABEL', {'High light', 'White light', 'Low light', 'Shade'}, ...
    'STRESS_COLOUR', {'#E64B35FF', '#7E6148FF', '#4DBBD5FF', '#3C5488FF'}, ...
    'STRESS_SHAPE', {'square', 'circle', 'triangle', 'diamond'}, ...
    'DIRECTORY_UTIL_R', [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'utilities'], ...
    'DIRECTORY_ANALYSIS', [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'study_LightStress' filesep 'analysis'], ...
    'DIRECTORY_FIG', [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'study_LightStress']);

nne.memorize('LATENT_REP');
nne.get('PLOT_R_PALETTE');
nne.get('PLOT_R_LS_QNORM_MED');

%% save as b2 file
fprintf('pipeline saving...\n')
tic
mkdir([fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'study_LightStress' filesep 'trained_b2_files']);
Element.save(nne, [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'study_LightStress' filesep 'trained_b2_files' filesep 'nne.b2']);
toc
fprintf('pipeline saved\n')

%% reconstruct the data
saved_b2 = [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'study_LightStress' filesep 'trained_b2_files' filesep 'nne.b2']; % the model saved above
nne = Element.load(saved_b2);
nne_update = NNVariationalAutoencoderEvaluator_RS( ...
    'NN', nne.get('NN'), ...
    'D', d_fig, ...
    'DPROC', dproc, ...
    'RESOLUTION_CM', 6, ...
    'IDX_LABEL_KIND', 1, ...
    'IDX_LABEL_STRESS', 2, ...
    'IDX_LABEL_LOCATION', 3, ...
    'STRESS_SEQ', {'HL', 'WL', 'LL', 'SH'}, ...
    'STRESS_LABEL', {'High light', 'White light', 'Low light', 'Shade'}, ...
    'STRESS_COLOUR', {'#E64B35FF', '#7E6148FF', '#4DBBD5FF', '#3C5488FF'}, ...
    'STRESS_SHAPE', {'square', 'circle', 'triangle', 'diamond'}, ...
    'DIRECTORY_UTIL_R', [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'utilities'], ...
    'DIRECTORY_ANALYSIS', [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'study_LightStress' filesep 'analysis'], ...
    'DIRECTORY_FIG', [fileparts(which('NNDatasetProcess_RamanSpectra')) filesep 'study_LightStress']);

detransformation = true;
denormalization = true;
representation_select = 'median';
outdir_prefix = 'crnr_detransformed';
recons_data = nne_update.get('DATA_RECONSTRUCTION', outdir_prefix, representation_select, denormalization, detransformation);

