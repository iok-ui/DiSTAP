	assert(nncv.get('DETECT_PLATEAU', steep_loss(1:100), 10, 0.001, 20) == 100, ...
	    [BRAPH2.STR ':NNVariationalAutoencoderMLP_CV:' BRAPH2.FAIL_TEST], ...
